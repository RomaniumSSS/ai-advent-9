"""День 8: счёт токенов ДО вызова. Без API вообще.

Единственное место в проекте, где написано слово `tiktoken`. Всё остальное —
`agent.py`, `cli.py`, `web.py` — работает с готовым `Budget` и не знает, чем он
посчитан. Поменять токенизатор на родной словарь DeepSeek или на HTTP-эндпоинт
провайдера можно, не открывая остальные файлы.

Зачем это вообще нужно, если `usage.prompt_tokens` приезжает с ответом. Затем,
что `usage` — счёт постфактум: он говорит, сколько вы уже заплатили, и приходит
вместе с оплаченным ответом. Здесь считается то же самое ДО отправки, и только
поэтому появляется возможность не отправлять. Плюс `usage` отдаёт одно число на
весь запрос: разложить его на «роль / история / новый вопрос» провайдер не даёт,
а именно этого просит задание дня 8.

Три решения, которые легко принять наоборот:

- **это ОЦЕНКА, и слово выбрано не из скромности.** `o200k_base` — словарь
  OpenAI. У DeepSeek, GLM и Kimi словари свои, и на одном и том же тексте они
  дают другое число. Поэтому каждая оценка живёт рядом с фактическим
  `prompt_tokens`, а расхождение печатается в проценах: счётчик, который никогда
  не сверяют, врёт ровно столько, сколько хочет, и никто об этом не узнаёт;
- **накладные на разметку сообщений — отдельное слагаемое, а не поправка внутри.**
  Провайдер оборачивает каждую реплику маркерами роли, и в разговоре из полусотни
  коротких ходов эта обёртка весит больше, чем текст последнего вопроса. Спрятать
  её внутрь `history` значило бы соврать, что история такая тяжёлая сама по себе,
  и увести человека сокращать не то;
- **потолок ответа входит в бюджет.** Окно модели общее на вход и на выход: если
  влезает только запрос, а на ответ не остаётся, провайдер откажет — при том что
  «промпт помещается» будет чистой правдой. Считать надо `prompt + max_tokens`.

Кодировка тянется с сети при первом обращении и потом лежит в кеше tiktoken.
Оффлайн на чистой машине первый вызов упадёт — это осознанная плата за то,
чтобы не тащить словарь в репозиторий.
"""

from dataclasses import dataclass

import tiktoken

# Словарь новых моделей OpenAI. Для моделей каталога — приближение, см. шапку.
ENCODING_NAME = "o200k_base"

# Служебная обёртка одной реплики: маркер начала, имя роли, разделитель, маркер
# конца. Число из документации OpenAI по подсчёту токенов чата; для чужих моделей
# оно тоже приближение, и меняет оно немного — но в длинной истории умножается
# на число сообщений, а не на число символов, и именно поэтому заметно.
PER_MESSAGE_OVERHEAD = 4

# Затравка ответа: провайдер сам дописывает в конец запроса начало реплики
# ассистента. Одна на весь запрос, а не на сообщение.
PRIMING_OVERHEAD = 3

_encoder = None


def encoder():
    """Кодировка процесса. Грузится при первом вызове, а не при импорте.

    Первый вызов может уйти в сеть за словарём, и делать это на строке импорта
    значило бы, что модуль нельзя прочитать без интернета — включая офлайн-тесты,
    которым сеть не нужна вовсе.
    """
    global _encoder
    if _encoder is None:
        _encoder = tiktoken.get_encoding(ENCODING_NAME)
    return _encoder


def count_text(text: str) -> int:
    """Токены голого текста, без обёртки роли."""
    if not text:
        return 0
    return len(encoder().encode(text))


def count_messages(messages: list[dict]) -> int:
    """Токены списка сообщений так, как его увидит провайдер: текст плюс разметка."""
    total = PRIMING_OVERHEAD
    for message in messages:
        total += PER_MESSAGE_OVERHEAD + count_text(message.get("content", ""))
    return total


@dataclass(frozen=True)
class Budget:
    """Из чего состоит запрос и влезает ли он в окно.

    Четыре слагаемых вместо одного числа затем, что решение о том, что резать,
    зависит от того, что именно распухло. Раздутая роль лечится переписыванием
    промпта, раздутая история — новой сессией или сжатием, раздутый вопрос —
    вопросом покороче. Одно общее «12400 токенов» не подсказывает ничего.

    `limit` = None означает «окно неизвестно». Это честное состояние, а не
    недоделка: настоящие окна моделей каталога мы не сверяли, а выдуманное число
    в роли ограничителя хуже отсутствующего — оно выглядит как факт.
    """

    system: int
    history: int
    question: int
    overhead: int
    reserved: int
    limit: int | None = None

    @property
    def prompt(self) -> int:
        """Всё, что уедет в модель на этом ходу. Ровно то, что вернётся в
        `usage.prompt_tokens`, — если бы наш словарь совпадал с чужим."""
        return self.system + self.history + self.question + self.overhead

    @property
    def total(self) -> int:
        """Вход плюс место под ответ. Окно у модели одно на оба."""
        return self.prompt + self.reserved

    @property
    def fits(self) -> bool:
        return self.limit is None or self.total <= self.limit

    @property
    def free(self) -> int | None:
        """Сколько ещё влезет. Отрицательное число — на столько уже вылезли."""
        return None if self.limit is None else self.limit - self.total

    @property
    def history_share(self) -> float:
        """Доля истории во входе. Число, ради которого день 8 и затевался:
        оно растёт с каждым ходом, и платить приходится за него, а не за вопрос."""
        return 0.0 if self.prompt == 0 else self.history / self.prompt

    def line(self) -> str:
        """Одна строка на экран: из чего сложился запрос."""
        parts = (
            f"роль {self.system} + история {self.history} + вопрос {self.question}"
            f" + разметка {self.overhead} = {self.prompt}"
        )
        if self.limit is None:
            return f"оценка входа: {parts}; на ответ ещё {self.reserved}"
        return (
            f"оценка входа: {parts}; +{self.reserved} на ответ = {self.total}"
            f" из {self.limit} (свободно {self.free})"
        )


def drift(estimate: int, actual: int | None) -> float | None:
    """На сколько процентов наша оценка разошлась с фактом провайдера.

    None, если сверять не с чем: ноль здесь означал бы идеальное попадание,
    то есть выдал бы отсутствие проверки за её лучший возможный исход.
    """
    if not actual:
        return None
    return (estimate - actual) / actual * 100
