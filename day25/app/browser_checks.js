async (page) => {
  const check=(condition,message)=>{if(!condition)throw Error(message);};
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1280,height:800});
  await page.goto('http://127.0.0.1:8053/');
  await page.locator('#fixture-banner').waitFor({state:'visible'});
  const title='RAG учебный сценарий '+Date.now();
  await page.locator('#chat-title').fill(title);
  await page.locator('#create-chat').click();
  await page.waitForFunction(title=>document.getElementById('chat-heading').textContent===title,title);
  await page.locator('#memory-editor > summary').click();
  await page.locator('#goal').fill('Разобраться в RAG');
  await page.locator('#clarifications').fill('На Python');
  await page.locator('#constraints').fill('Кратко\nБез кода');
  await page.locator('#save-memory').click();
  await page.waitForFunction(()=>document.getElementById('memory-status').textContent.includes('версия 1'));
  await page.locator('#question').fill('Какие требования задания дня 18?');
  await page.locator('#send').click();
  await page.waitForFunction(()=>document.querySelectorAll('.turn').length===1 && !document.getElementById('send').disabled);
  check(await page.locator('.answer-text').count()===1,'answer missing');
  check(await page.locator('.answer-evidence .citation').count()===1,'quote missing');
  await page.locator('.source-link').first().click();
  check(await page.locator('.source').first().isVisible(),'source open failed');
  check(await page.evaluate(()=>window.pwned===undefined),'source XSS executed');
  await page.locator('#question').fill('а это?');
  await page.locator('#send').click();
  await page.waitForFunction(()=>document.querySelectorAll('.turn').length===2 && !document.getElementById('send').disabled);
  const firstChat=await page.locator('#chats button[aria-pressed=true]').getAttribute('data-chat-id');
  const metricsBefore=await page.evaluate(async()=> (await (await fetch('/api/state')).json()).test_metrics);
  await page.reload();
  await page.waitForFunction(()=>document.querySelectorAll('.turn').length===2);
  check(await page.locator('#goal').inputValue()==='Разобраться в RAG','memory lost on reload');
  const metricsAfter=await page.evaluate(async()=> (await (await fetch('/api/state')).json()).test_metrics);
  check(JSON.stringify(metricsBefore)===JSON.stringify(metricsAfter),'reload performed generation/search');
  await page.locator('#chat-title').fill('Другой разговор');
  await page.locator('#create-chat').click();
  await page.waitForFunction(()=>document.getElementById('chat-heading').textContent==='Другой разговор');
  check(await page.locator('.turn').count()===0,'foreign archive leak');
  check(await page.locator('#goal').inputValue()==='','foreign memory leak');
  await page.locator('#chats button[data-chat-id="'+firstChat+'"]').click();
  await page.waitForFunction(()=>document.querySelectorAll('.turn').length===2);
  check(await page.locator('#chats button[aria-pressed=true]').getAttribute('data-chat-id')===firstChat,'wrong selected chat');
  await page.locator('#question').fill('нет сведений');await page.locator('#send').click();
  await page.waitForFunction(()=>document.querySelectorAll('.turn').length===3 && !document.getElementById('send').disabled);
  check((await page.locator('.turn').last().textContent()).includes('Недостаточный контекст'),'refusal not visible');
  await page.locator('#question').fill('неверная цитата');await page.locator('#send').click();
  await page.waitForFunction(()=>document.querySelectorAll('.turn').length===4 && !document.getElementById('send').disabled);
  check((await page.locator('.turn').last().textContent()).includes('Непроверенный ответ'),'invalid answer appears verified');
  check(await page.locator('.turn').last().locator('.answer-text').count()===0,'invalid answer displayed as final');
  await page.locator('#memory-editor').evaluate(el=>el.open=true);
  await page.locator('#clear-memory').click();
  await page.waitForFunction(()=>document.getElementById('memory-status').textContent.includes('Записи удалены'));
  check(await page.locator('#goal').inputValue()==='','memory clear failed');
  await page.locator('#goal').fill('Учиться короткими шагами');await page.locator('#save-memory').click();
  await page.waitForFunction(()=>document.getElementById('memory-status').textContent.includes('версия 3'));
  await page.locator('#memory-editor').evaluate(el=>el.open=false);
  await page.evaluate(()=>window.scrollTo(0,0));
  check(errors.length===0,'browser errors: '+errors.join('; '));
  return {checks:'PASS: create/edit/clear/version, chat isolation/switch, ask/followup, quotes/source/XSS, reload no calls, refusal/unverified',firstChat,metrics:await page.evaluate(async()=> (await (await fetch('/api/state')).json()).test_metrics),pageErrors:errors};
}
