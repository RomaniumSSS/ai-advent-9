"""Profile11: лимиты стадий provider и согласованные ожидания lifecycle."""
EMBEDDING_DEADLINE_SECONDS=300
SELECTION_DEADLINE_SECONDS=300
SYNTHESIS_DEADLINE_SECONDS=300
SYNTHESIS_OUTPUT_TOKENS=1024
PROVIDER_TOTAL_BOUND_SECONDS=EMBEDDING_DEADLINE_SECONDS+SELECTION_DEADLINE_SECONDS+SYNTHESIS_DEADLINE_SECONDS
WORKER_JOIN_SECONDS=PROVIDER_TOTAL_BOUND_SECONDS+10
LAUNCHD_EXIT_TIMEOUT_SECONDS=PROVIDER_TOTAL_BOUND_SECONDS+20
POLL_TIMEOUT_SECONDS=PROVIDER_TOTAL_BOUND_SECONDS+30

def provider_deadline_cap(stage='default'):
    if stage=='synthesis':return SYNTHESIS_DEADLINE_SECONDS
    if stage=='embedding':return EMBEDDING_DEADLINE_SECONDS
    return SELECTION_DEADLINE_SECONDS
